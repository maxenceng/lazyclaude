import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const SCHEMA = new URL('../../docs/protocol/protocol.schema.json', import.meta.url);
const OUT = new URL('../src/protocol/generated/protocol.ts', import.meta.url);

const schema = JSON.parse(await readFile(SCHEMA, 'utf8'));
const version = schema.properties.notifications.properties.ready.properties.params.properties.protocol.const;

const types = await compile(schema, 'Protocol', {
  additionalProperties: false,
  declareExternallyReferenced: true,
  format: true,
  bannerComment: '',
  style: { singleQuote: true },
});

const body = `// Generated by scripts/generate-protocol.mjs from docs/protocol/protocol.schema.json. Never edit.

export const PROTOCOL_VERSION = ${version};

${types}
export type MethodName = keyof LazyclaudeProtocol['methods'];
export type InputName = keyof LazyclaudeProtocol['inputs'];
export type NotificationName = keyof LazyclaudeProtocol['notifications'];
export type Params<M extends MethodName> = LazyclaudeProtocol['methods'][M]['params'];
export type Result<M extends MethodName> = LazyclaudeProtocol['methods'][M]['result'];
export type InputParams<I extends InputName> = LazyclaudeProtocol['inputs'][I]['params'];
export type NotificationParams<N extends NotificationName> = LazyclaudeProtocol['notifications'][N]['params'];
`;

await writeFile(OUT, body);
