import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import dev.maxenceng.lazyclaude.session.domain.NoTranscript;
import dev.maxenceng.lazyclaude.session.domain.ReadEntries;
import dev.maxenceng.lazyclaude.session.domain.TranscriptUnreadableException;
import dev.maxenceng.lazyclaude.session.published.TranscriptOffset;

class TranscriptReadRepositoryTest {

    private static final String SESSION = "70c67de2-4563-47c2-b946-eb5198915ba2";

    @TempDir
    Path projects;

    private TranscriptReadRepository repository;

    @BeforeEach
    void setUp() {
        repository = new TranscriptReadRepository(projects);
    }

    @Test
    void shouldReadPromptsRepliesAndToolCallsInTheOrderTheyWereWritten() throws IOException {
        writeTranscript(
                projects,
                folder(),
                SESSION,
                userLine(cwd(), started(), "fix the status line"),
                assistantTextLine("Looking at it."),
                toolUseLine("Bash", "{\"command\":\"make test\"}"),
                assistantTextLine("All green."));

        assertThat(entriesFrom(repository, TranscriptOffset.start()))
                .containsExactly(
                        prompt("fix the status line"),
                        reply("Looking at it."),
                        toolCall("Bash", "make test"),
                        reply("All green."));
    }

    @Test
    void shouldHideToolResultsThinkingAndMetaPrompts() throws IOException {
        writeTranscript(
                projects,
                folder(),
                SESSION,
                metaLine(cwd(), started(), "caveat: the messages below were generated by the user"),
                userLine(cwd(), started(), "go"),
                thinkingLine("the user wants it fast"),
                toolUseLine("Read", "{\"file_path\":\"/work/app/pom.xml\"}"),
                toolResultLine(cwd(), started()),
                assistantTextLine("Done."));

        assertThat(entriesFrom(repository, TranscriptOffset.start()))
                .containsExactly(prompt("go"), toolCall("Read", "/work/app/pom.xml"), reply("Done."));
    }

    @Test
    void shouldReadAPromptGivenAsTextBlocks() throws IOException {
        writeTranscript(projects, folder(), SESSION, userLineWithBlocks(cwd(), started(), "look at this"));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(prompt("look at this"));
    }

    @Test
    void shouldSkipATextBlockThatSaysNothing() throws IOException {
        writeTranscript(projects, folder(), SESSION, assistantTextLine("  \n "), assistantTextLine("Hi."));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(reply("Hi."));
    }

    @Test
    void shouldSkipALineThatIsNotJson() throws IOException {
        writeTranscript(projects, folder(), SESSION, notJsonLine(), assistantTextLine("Hi."));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(reply("Hi."));
    }

    @Test
    void shouldShowTheFirstArgumentThatSaysWhatTheToolDoes() throws IOException {
        writeTranscript(
                projects,
                folder(),
                SESSION,
                toolUseLine("Grep", "{\"pattern\":\"TODO\",\"path\":\"/work/app\"}"),
                toolUseLine("ToolSearch", "{\"query\":\"select:WebFetch\",\"max_results\":1}"),
                toolUseLine("mcp__notes__add", "{\"limit\":3,\"title\":\"buy milk\"}"),
                toolUseLine("EnterPlanMode", "{}"));

        assertThat(entriesFrom(repository, TranscriptOffset.start()))
                .containsExactly(
                        toolCall("Grep", "TODO"),
                        toolCall("ToolSearch", "select:WebFetch"),
                        toolCall("mcp__notes__add", "buy milk"),
                        toolCallWithoutArgument("EnterPlanMode"));
    }

    @Test
    void shouldCollapseAMultiLineArgumentToOneLine() throws IOException {
        writeTranscript(
                projects, folder(), SESSION, toolUseLine("Bash", "{\"command\":\"git add -A\\n  && git commit\"}"));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(toolCall("Bash", "git add -A && git commit"));
    }

    @Test
    void shouldContinueAfterTheOffsetItHandedBack() throws IOException {
        Path file = writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "first"));
        ReadEntries first = (ReadEntries) readFrom(repository, TranscriptOffset.start());
        append(file, assistantTextLine("second"));

        ReadEntries next = (ReadEntries) readFrom(repository, first.next());

        assertThat(next.entries()).containsExactly(reply("second"));
        assertThat(next.start()).as("the entries continue where the last read ended").isEqualTo(first.next());
    }

    @Test
    void shouldReadNothingAndKeepTheOffsetWhenItLandsExactlyAtTheEndOfTheFile() throws IOException {
        writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "first"));
        ReadEntries first = (ReadEntries) readFrom(repository, TranscriptOffset.start());

        ReadEntries again = (ReadEntries) readFrom(repository, first.next());

        assertThat(again.entries()).isEmpty();
        assertThat(again.next()).isEqualTo(first.next());
    }

    @Test
    void shouldLeaveALastLineWithNoNewlineForTheNextRead() throws IOException {
        Path file = writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "first"));
        append(file, "{\"type\":\"assistant\",\"message\":{\"content\":[{\"type\":\"text\",\"te");
        ReadEntries partial = (ReadEntries) readFrom(repository, TranscriptOffset.start());
        append(file, "xt\":\"whole\"}]}}\n");

        ReadEntries completed = (ReadEntries) readFrom(repository, partial.next());

        assertThat(partial.entries()).containsExactly(prompt("first"));
        assertThat(completed.entries()).as("the half-written line is taken whole once its newline arrives").containsExactly(reply("whole"));
    }

    @Test
    void shouldReadFromTheStartWhenTheFileIsShorterThanTheOffset() throws IOException {
        Path file = writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "a long first prompt indeed"));
        ReadEntries first = (ReadEntries) readFrom(repository, TranscriptOffset.start());
        rewriteInPlace(file, userLine(cwd(), started(), "new"));

        ReadEntries again = (ReadEntries) readFrom(repository, first.next());

        assertThat(again.entries()).containsExactly(prompt("new"));
        assertThat(again.start()).as("the shell replaces what it showed when the entries start again at the beginning").isEqualTo(TranscriptOffset.start());
    }

    @Test
    void shouldCountBytesNotCharactersInTheOffset() throws IOException {
        Path file = writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "é"));
        ReadEntries first = (ReadEntries) readFrom(repository, TranscriptOffset.start());
        append(file, assistantTextLine("ça va"));

        assertThat(((ReadEntries) readFrom(repository, first.next())).entries()).containsExactly(reply("ça va"));
    }

    @Test
    void shouldFindTheTranscriptInTheFolderOfTheDirectoryItsSessionStartedIn() throws IOException {
        writeTranscript(projects, "-work-my-app-x", SESSION, assistantTextLine("found"));

        assertThat(repository.read(sessionId(), workingDirectoryAt("/work/my.app_x"), TranscriptOffset.start()))
                .isInstanceOf(ReadEntries.class)
                .extracting(read -> ((ReadEntries) read).entries())
                .isEqualTo(List.of(reply("found")));
    }

    @Test
    void shouldFindTheTranscriptBySessionIdInAnotherFolderWhenTheSessionMovedDirectory() throws IOException {
        writeTranscript(projects, "-work-app-subdir", SESSION, assistantTextLine("moved"));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(reply("moved"));
    }

    @Test
    void shouldSayThereIsNoTranscriptYetWhenNoFolderHoldsOne() throws IOException {
        Files.createDirectories(projects.resolve(folder()));

        assertThat(readFrom(repository, TranscriptOffset.start())).isEqualTo(new NoTranscript());
    }

    @Test
    void shouldSayThereIsNoTranscriptYetWhenTheRootDoesNotExist() {
        assertThat(new TranscriptReadRepository(projects.resolve("missing")).read(sessionId(), workingDirectoryAt(cwd()), TranscriptOffset.start()))
                .isEqualTo(new NoTranscript());
    }

    @Test
    void shouldFillInOnceTheTranscriptAppears() throws IOException {
        assertThat(readFrom(repository, TranscriptOffset.start())).isEqualTo(new NoTranscript());

        writeTranscript(projects, folder(), SESSION, userLine(cwd(), started(), "hello"));

        assertThat(entriesFrom(repository, TranscriptOffset.start())).containsExactly(prompt("hello"));
    }

    @Test
    void shouldReadNoTranscriptOfAnotherSession() throws IOException {
        writeTranscript(projects, folder(), "9b1e44d2-77aa-4c3f-8d20-5a6c0b1f2e33", userLine(cwd(), started(), "not mine"));

        assertThat(readFrom(repository, TranscriptOffset.start())).isEqualTo(new NoTranscript());
    }

    @Test
    void shouldSayWhyTheTranscriptsCannotBeListed() throws IOException {
        Path file = Files.writeString(projects.resolve("projects-file"), "not a directory");

        assertThatThrownBy(() -> new TranscriptReadRepository(file).read(sessionId(), workingDirectoryAt(cwd()), TranscriptOffset.start()))
                .isInstanceOf(TranscriptUnreadableException.class)
                .hasMessageContaining("projects-file");
    }
}
